def mirror(left, width):
    rows = {}
    for y, s in left.items():
        row = list(s.ljust(width, '.'))
        for x, ch in enumerate(s):
            if ch == '#': row[width - 1 - x] = '#'
        rows[y] = ''.join(row)
    return rows

